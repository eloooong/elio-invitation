import fs from 'node:fs/promises';

// Rebuild only the inline walking cutouts. The hero/footer keep their original art.
const rigs = JSON.parse(await fs.readFile('assets/safari-walk-rig.json', 'utf8'));
const poses = (await fs.readFile('assets/safari-walking-poses.png')).toString('base64');
const definitions = [`<image id="safari-walk-poses" width="1536" height="1024" href="data:image/png;base64,${poses}" />`];
const symbols = [];
for (const [species, rig] of Object.entries(rigs)) {
  const atlas = rig.atlas || 'safari-atlas';
  const [left, top, right, bottom] = rig.box;
  const x = left - 22, y = top - 6, w = right - left + 44, h = bottom - top + 14;
  const id = `walk-${species}`;
  definitions.push(`<mask id="${id}-body" maskUnits="userSpaceOnUse" x="${x}" y="${y}" width="${w}" height="${h}" style="mask-type:luminance"><rect x="${x}" y="${y}" width="${w}" height="${h}" fill="white"/>${rig.parts.map(p => `<path d="${p.cut}" fill="black"/>`).join('')}</mask>`);
  // The full atlas is clipped explicitly; SVG letterboxing must never expose a neighbor.
  definitions.push(`<clipPath id="${id}-crop"><rect x="${left - 3}" y="${top - 3}" width="${right-left+6}" height="${bottom-top+6}"/></clipPath>`);
  for (const part of rig.parts) {
    definitions.push(`<clipPath id="${id}-${part.name}-clip"><path d="${part.path}"/></clipPath>`);
    if (part.collar) definitions.push(`<clipPath id="${id}-${part.name}-collar"><path d="${part.collar}"/></clipPath>`);
  }
  const moving = layer => rig.parts.filter(p => p.layer === layer).map(part => `<g class="walk-limb" data-species="${species}" data-pivot="${part.pivot.join(',')}" data-phase="${part.phase}" data-swing="${rig.swing || 8}" data-lift="${rig.lift || 5}" data-cycle="${rig.cycle}" data-foot-y="${bottom}" transform="rotate(0 ${part.pivot.join(' ')})"><g clip-path="url(#${id}-${part.name}-clip)"><use href="#${atlas}"/></g></g>`).join('');
  const collars = layer => rig.parts.filter(p => p.layer === layer && p.collar).map(part => `<g clip-path="url(#${id}-${part.name}-clip)"><g clip-path="url(#${id}-${part.name}-collar)"><use href="#${atlas}"/></g></g>`).join('');
  symbols.push(`<symbol id="${id}" viewBox="${x} ${y} ${w} ${h}" preserveAspectRatio="xMidYMax meet" overflow="visible">${moving('far')}<g clip-path="url(#${id}-crop)"><g mask="url(#${id}-body)"><use href="#${atlas}"/></g></g>${collars('far')}${moving('near')}${collars('near')}</symbol>`);
}
const block = `<!-- Painted walking assets: generated by scripts/build-walk-assets.mjs. -->\n<g id="painted-walk-assets">\n${definitions.join('\n')}\n${symbols.join('\n')}\n</g>\n<!-- /Painted walking assets -->`;
let html = await fs.readFile('index.html', 'utf8');
const existing = /<!-- Painted walking assets:[\s\S]*?<!-- \/Painted walking assets -->/;
if (existing.test(html)) html = html.replace(existing, () => block);
else html = html.replace('      <defs>', () => `      <defs>\n${block}`);
await fs.writeFile('index.html', html);
console.log(`Built ${symbols.length} painted walking rigs.`);
