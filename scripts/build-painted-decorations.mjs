import fs from 'node:fs/promises';

const boxes = JSON.parse(await fs.readFile('assets/safari-decorations-map.json', 'utf8'));
const encoded = (await fs.readFile('assets/safari-painted-decorations.webp')).toString('base64');
let html = await fs.readFile('index.html', 'utf8');
html = html.replace(/<!-- Painted decoration atlas:[\s\S]*?<!-- \/Painted decoration atlas -->\n?/, '');
const defs = [`<image id="painted-decor-atlas" width="1254" height="1254" href="data:image/webp;base64,${encoded}"/>`];
const newSymbols = [];
for (const [name, [x, y, right, bottom]] of Object.entries(boxes)) {
  const w = right - x, h = bottom - y, clip = `painted-crop-${name}`;
  defs.push(`<clipPath id="${clip}"><rect width="${w}" height="${h}"/></clipPath>`);
  const pixels = `<use href="#painted-decor-atlas" x="${-x}" y="${-y}"/>`;
  let drawing = pixels;
  if (name === 'butterfly') {
    const cx = 775 - x, cy = 804 - y;
    defs.push(`<clipPath id="painted-butterfly-left"><rect width="${cx}" height="${h}"/></clipPath><clipPath id="painted-butterfly-right"><rect x="${cx}" width="${w-cx}" height="${h}"/></clipPath><clipPath id="painted-butterfly-body"><rect x="${cx-6}" width="12" height="${h}"/></clipPath>`);
    drawing = `<g class="butterfly-wing" style="transform-origin:${cx}px ${cy}px"><g clip-path="url(#painted-butterfly-left)">${pixels}</g></g><g class="butterfly-wing" style="transform-origin:${cx}px ${cy}px;--wing-delay:-.08s"><g clip-path="url(#painted-butterfly-right)">${pixels}</g></g><g clip-path="url(#painted-butterfly-body)">${pixels}</g>`;
  }
  const ratio = name === 'painted-meadow' ? 'none' : ['tree','painted-grass','painted-seedgrass'].includes(name) ? 'xMidYMax meet' : 'xMidYMid meet';
  const symbol = `<symbol id="${name}" viewBox="0 0 ${w} ${h}" overflow="hidden" preserveAspectRatio="${ratio}"><g clip-path="url(#${clip})">${drawing}</g></symbol>`;
  const existing = new RegExp(`<symbol id="${name}"[^>]*>[\\s\\S]*?<\\/symbol>`);
  if (existing.test(html)) html = html.replace(existing, () => symbol);
  else newSymbols.push(symbol);
}
const block = `<!-- Painted decoration atlas: generated by scripts/build-painted-decorations.mjs. -->\n${defs.join('\n')}\n${newSymbols.join('\n')}\n<!-- /Painted decoration atlas -->\n`;
html = html.replace('      <defs>', () => `      <defs>\n${block}`);
await fs.writeFile('index.html', html);
console.log('Embedded sixteen matching painted decorations.');
