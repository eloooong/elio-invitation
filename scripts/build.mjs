import fs from 'node:fs/promises';
import vm from 'node:vm';
import {externalizeMedia} from './externalize-media.mjs';
import {addSharePreview} from './share-preview.mjs';

// Build the approved paper-cut design, retaining the original as its source.
await import('../paper-cut-preview/build.mjs');
const source = await fs.readFile('paper-cut-preview/index.html', 'utf8');
const script = source.match(/<script id="invitation-config">([\s\S]*?)<\/script>/)[1];
const context = { localStorage: { getItem: () => null }, document: { querySelector: () => null } };
vm.createContext(context);
vm.runInContext(script + ';globalThis.seed = JSON.parse(JSON.stringify(CONFIG));', context);
const seed = context.seed;
delete seed.hostPasscode;
const validator = script.slice(script.indexOf('function validateInvitation('), script.indexOf('\n      try {', script.indexOf('function validateInvitation(')));
const icons = script.slice(script.indexOf('const DEFAULT_TRAIL_ICONS'), script.indexOf('CONFIG.schedule ='));
await fs.mkdir('server', { recursive: true });
await fs.writeFile('server/invitation.js', '// Generated by npm run build from the invitation defaults.\nexport const defaults = ' + JSON.stringify(seed) + ';\nconst CONFIG = defaults;\n' + icons + '\nexport ' + validator.trim() + '\n');
await fs.mkdir('dist', { recursive: true });
let output = source.replace(/hostPasscode: "[^"]*",/, 'hostPasscode: "",');
output = output.replaceAll('elio-paper-preview-', 'elio-safari-');
const pageTitle = `${seed.child}'s First Birthday`.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;');
output = output.replace(/<title>[^<]*<\/title>/, `<title>${pageTitle}</title>`);
output = output.replace("'s First Safari · Local preview", "'s First Birthday");
// Cloud mode keeps the existing server-side invitation and shared RSVPs.
output = output.replace('<head>', '<head>\n    <meta name="elio-backend" content="cloud" />\n    <meta name="robots" content="noindex, nofollow" />');
// The full embedded version is fetched only when a host downloads an offline copy.
await fs.writeFile('dist/offline-template.html', output);
const optimized=await externalizeMedia(output,'dist');
optimized.html=await addSharePreview(optimized.html,seed);
await fs.writeFile('dist/index.html', optimized.html);
console.log(`Production page: ${Buffer.byteLength(optimized.html)} bytes; ${optimized.files} independently cached media files.`);
// A 404 page prevents Pages' automatic SPA fallback from masking missing/private files.
await fs.writeFile('dist/404.html', '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="robots" content="noindex,nofollow"><title>Trail not found</title><style>body{margin:0;background:#faf6e9;color:#263b2c;font:18px/1.6 system-ui,sans-serif;display:grid;min-height:100vh;place-items:center}main{max-width:32rem;padding:2rem;text-align:center}a{color:#276346;font-weight:600}</style></head><body><main><p>EXPEDITION DETOUR</p><h1>This trail doesn’t exist.</h1><p>Let’s head back to Elio’s invitation.</p><a href="/">Back to the invitation</a></main></body></html>');
await fs.writeFile('dist/_routes.json', JSON.stringify({ version: 1, include: ['/api/*'], exclude: [] }, null, 2));
await fs.writeFile('dist/_headers', `/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: DENY
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  X-Robots-Tag: noindex, nofollow
/index.html
  Cache-Control: no-cache
/media/*
  Cache-Control: public, max-age=31536000, immutable
/
  Cache-Control: no-cache
`);
console.log('Built invitation frontend and server defaults for Cloudflare Pages or Vercel. Private files are excluded.');
